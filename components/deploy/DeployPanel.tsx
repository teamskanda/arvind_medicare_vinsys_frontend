import { Button } from "@/components/ui/Button";
import { Callout } from "@/components/ui/Callout";
import { CopyButton } from "@/components/ui/CopyButton";
import { ApiError, api } from "@/lib/api";
import { cn } from "@/lib/utils";
import type {
  Chatbot,
  DeploymentInfo,
  DeploymentMode,
  DeploymentSnippet,
} from "@/types";

/**
 * The Deploy tab: publish state, the three install options, and a live preview.
 *
 * Every URL and every code snippet here is generated by the backend from the
 * chatbot's `public_id` and the configured deployment base URL. Nothing is
 * assembled in the browser, so the dashboard cannot show a URL that differs
 * from the one the server will actually serve.
 */

const MODE_ICONS: Record<DeploymentMode, typeof MessageCircle> = {
  widget: MessageCircle,
  iframe: Square,
  link: Link2,
};

export function DeployPanel({ chatbot }: { chatbot: Chatbot }) {
  const chatbotId = chatbot.id;

  const [info, setInfo] = useState<DeploymentInfo | null>(null);
  const [loadError, setLoadError] = useState<string | null>(null);
  const [actionError, setActionError] = useState<string | null>(null);
  const [working, setWorking] = useState(false);
  const [domains, setDomains] = useState("");
  /**
   * Set only on the false -> true transition, so the card celebrates the act
   * of publishing rather than the state of being published. Opening this tab
   * on an assistant that went live last week should be quiet.
   */
  const [justPublished, setJustPublished] = useState(false);

  useEffect(() => {
    if (!justPublished) return;
    const timer = setTimeout(() => setJustPublished(false), 2400);
    return () => clearTimeout(timer);
  }, [justPublished]);

  const load = useCallback(async () => {
    try {
      setLoadError(null);
      const next = await api.getDeployment(chatbotId);
      setInfo(next);
      setDomains(next.allowed_domains.join("\n"));
    } catch (error) {
      setLoadError(
        error instanceof ApiError
          ? error.message
          : "Could not load the deployment settings.",
      );
    }
  }, [chatbotId]);

  useEffect(() => {
    void load();
  }, [load]);

  async function onPublish() {
    setWorking(true);
    setActionError(null);
    try {
      const next = await api.publishChatbot(chatbotId, domains.split(/[\n,]+/).map((value) => value.trim()).filter(Boolean));
      if (next.is_published && !info?.is_published) setJustPublished(true);
      setInfo(next);
      setDomains(next.allowed_domains.join("\n"));
    } catch (error) {
      setActionError(
        error instanceof ApiError ? error.message : "Could not publish this assistant.",
      );
    } finally {
      setWorking(false);
    }
  }

  async function onUnpublish() {
    setWorking(true);
    setActionError(null);
    try {
      setInfo(await api.unpublishChatbot(chatbotId));
    } catch (error) {
      setActionError(
        error instanceof ApiError ? error.message : "Could not unpublish this assistant.",
      );
    } finally {
      setWorking(false);
    }
  }

  if (loadError) return <Callout tone="error">{loadError}</Callout>;

  if (!info) {
    return (
      <div className="app-skeleton h-96 rounded-card border border-ink-100 bg-surface" />
    );
  }

  return (
    <div className="space-y-5">
      <PublicationCard
        info={info}
        working={working}
        justPublished={justPublished}
        onPublish={onPublish}
        onUnpublish={onUnpublish}
      />

      {actionError ? <Callout tone="error">{actionError}</Callout> : null}

      <div className="grid gap-5 lg:grid-cols-[1fr_340px]">
        <div className="min-w-0 space-y-4">
          {info.snippets.map((snippet) => (
            <SnippetCard
              key={snippet.mode}
              snippet={snippet}
              published={info.is_published}
            />
          ))}
          <PlatformNotes info={info} />
          <section className="rounded-card border border-ink-100 bg-surface p-4">
            <label htmlFor="embedding-websites" className="block text-sm font-semibold text-ink-900">Authorised embedding websites</label>
            <p id="embedding-websites-hint" className="my-2 text-sm text-ink-500">One domain per line, such as your-business.com. Leave empty to allow any website. Your standalone link keeps working. Only add websites you are authorised to use.</p>
            <textarea id="embedding-websites" aria-describedby="embedding-websites-hint" rows={3} value={domains} onChange={(event) => setDomains(event.target.value)} className="w-full rounded-lg border border-ink-200 p-3 text-sm" placeholder="your-business.com" />
            {domains !== info.allowed_domains.join("\n") && <Button className="mt-3" onClick={onPublish} loading={working} disabled={!info.can_publish}>Publish website restrictions</Button>}
            <p className="mt-2 text-xs text-ink-500">Publishing applies this list and your saved design together.</p>
          </section>
        </div>

        <Preview info={info} />
      </div>
    </div>
  );
}

/* ------------------------------------------------------------------ */
/* Publication status                                                  */
/* ------------------------------------------------------------------ */

function PublicationCard({
  info,
  working,
  justPublished,
  onPublish,
  onUnpublish,
}: {
  info: DeploymentInfo;
  working: boolean;
  justPublished: boolean;
  onPublish: () => void;
  onUnpublish: () => void;
}) {
  return (
    <section
      className={cn(
        "publish-card rounded-card border border-ink-100 bg-surface p-4",
        justPublished && "is-going-live",
      )}
    >
      <div className="flex flex-wrap items-start justify-between gap-4">
        <div className="min-w-0">
          <div className="flex items-center gap-2">
            <StatusDot published={info.is_published} />
            <h2 className="text-sm font-semibold text-ink-900">
              {info.is_published ? "Published" : statusLabel(info)}
            </h2>
          </div>
          <p className="mt-1.5 max-w-prose text-sm leading-relaxed text-ink-500">
            {info.is_published
              ? "Your assistant is live. Anyone with the link or the installed snippet can talk to it, and they do not need a SKANDA AI account."
              : "Your assistant is not reachable from outside this dashboard yet. Publishing activates the URL below — the same URL every time, so you only ever install the snippet once."}
          </p>
        </div>

        {info.is_published ? (
          <div className="flex flex-wrap gap-2">
          {info.has_unpublished_changes && <Button onClick={onPublish} loading={working} disabled={!info.can_publish}>Publish changes</Button>}
          <Button
            variant="danger"
            onClick={onUnpublish}
            loading={working}
            icon={<Power aria-hidden className="size-3.5" />}
          >
            Unpublish
          </Button>
          </div>
        ) : (
          <Button
            onClick={onPublish}
            loading={working}
            disabled={!info.can_publish}
            icon={<CheckCircle2 aria-hidden className="size-3.5" />}
          >
            Publish chatbot
          </Button>
        )}
      </div>

      {!info.is_published && info.publish_blocked_reason ? (
        <div className="mt-3">
          <Callout tone="warning" title="Not ready to publish">
            {info.publish_blocked_reason}
          </Callout>
        </div>
      ) : null}

      {info.is_published ? (
        <dl className="mt-4 grid gap-x-6 gap-y-2 border-t border-ink-100 pt-3 text-xs sm:grid-cols-2">
          <Fact label="Pages answering questions" value={`${info.included_pages}`} />
          <Fact
            label="Published"
            value={
              info.published_at
                ? new Date(info.published_at).toLocaleString()
                : "—"
            }
          />
        </dl>
      ) : null}

      {info.is_published && info.has_unpublished_changes ? (
        <div className="mt-3">
          <Callout tone="warning" title="You have changes that are not live yet">
            Your saved design differs from what visitors are being served.
            Publish again to apply it — the URL and the installed snippet do
            not change.
          </Callout>
        </div>
      ) : null}

      {!info.is_published && info.unpublished_at ? (
        <p className="mt-3 border-t border-ink-100 pt-3 text-xs text-ink-500">
          Unpublished on {new Date(info.unpublished_at).toLocaleString()}. Your
          settings, knowledge base and URL were all kept — publishing again
          restores exactly the same address.
        </p>
      ) : null}
    </section>
  );
}

function statusLabel(info: DeploymentInfo): string {
  if (info.status === "unpublished") return "Unpublished";
  if (info.status === "ready") return "Ready to publish";
  return "Draft";
}

function StatusDot({ published }: { published: boolean }) {
  return (
    <span
      aria-hidden
      className={cn(
        "size-2 rounded-full",
        // Rings in its own status colour while live. This is the dashboard's
        // only indicator that something is serving real visitors right now,
        // so it is worth it being visibly alive rather than a static dot.
        published ? "pulse-ring bg-success-700" : "bg-ink-300",
      )}
      style={
        published
          ? ({
              "--pulse-color": "var(--color-success-700)",
              "--pulse-scale": "2.8",
            } as React.CSSProperties)
          : undefined
      }
    />
  );
}

function Fact({ label, value }: { label: string; value: string }) {
  return (
    <div className="flex items-baseline justify-between gap-3">
      <dt className="text-ink-500">{label}</dt>
      <dd className="font-medium text-ink-900">{value}</dd>
    </div>
  );
}

/* ------------------------------------------------------------------ */
/* One deployment option                                               */
/* ------------------------------------------------------------------ */

function SnippetCard({
  snippet,
  published,
}: {
  snippet: DeploymentSnippet;
  published: boolean;
}) {
  const Icon = MODE_ICONS[snippet.mode];

  return (
    <section className="rounded-card border border-ink-100 bg-surface">
      <header className="flex flex-wrap items-start justify-between gap-3 border-b border-ink-100 px-4 py-3">
        <div className="min-w-0">
          <div className="flex items-center gap-2">
            <Icon aria-hidden className="size-4 shrink-0 text-burgundy-600" />
            <h3 className="text-sm font-semibold text-ink-900">{snippet.label}</h3>
            {snippet.recommended ? (
              <span className="inline-flex items-center gap-1 rounded-full bg-burgundy-50 px-2 py-0.5 text-[10px] font-semibold uppercase tracking-wide text-burgundy-700">
                <Star aria-hidden className="size-2.5" />
                Recommended
              </span>
            ) : null}
          </div>
          <p className="mt-1.5 max-w-prose text-xs leading-relaxed text-ink-500">
            {snippet.description}
          </p>
        </div>
      </header>

      <div className="space-y-3 px-4 py-3">
        <Row label={snippet.code ? "Assistant URL" : "Link to share"}>
          <code className="block min-w-0 flex-1 truncate rounded bg-ink-50 px-2 py-1.5 text-[11px] text-ink-700">
            {snippet.url}
          </code>
          <CopyButton value={snippet.url} label="Copy URL" />
          <Button
            variant="secondary"
            size="sm"
            onClick={() => window.open(snippet.url, "_blank", "noopener,noreferrer")}
            icon={<ExternalLink aria-hidden className="size-3.5" />}
          >
            Open
          </Button>
        </Row>

        {snippet.code ? (
          <div>
            <div className="mb-1.5 flex items-center justify-between gap-3">
              <span className="text-[11px] font-medium uppercase tracking-wide text-ink-500">
                Installation code
              </span>
              <CopyButton value={snippet.code} label="Copy code" />
            </div>
            <pre className="scrollbar-thin max-w-full overflow-x-auto rounded border border-ink-100 bg-ink-50 px-3 py-2.5 text-xs leading-relaxed text-ink-700">
              <code>{snippet.code}</code>
            </pre>
          </div>
        ) : null}

        {!published ? (
          <p className="flex items-start gap-1.5 text-[11px] text-warning-700">
            <TriangleAlert aria-hidden className="mt-px size-3 shrink-0" />
            You can install this now, but it will show an &ldquo;assistant
            unavailable&rdquo; message until you publish.
          </p>
        ) : null}
      </div>
    </section>
  );
}

function Row({
  label,
  children,
}: {
  label: string;
  children: React.ReactNode;
}) {
  return (
    <div>
      <span className="mb-1.5 block text-[11px] font-medium uppercase tracking-wide text-ink-500">
        {label}
      </span>
      <div className="flex flex-wrap items-center gap-2">{children}</div>
    </div>
  );
}

/* ------------------------------------------------------------------ */
/* Platform instructions                                               */
/* ------------------------------------------------------------------ */

function PlatformNotes({ info }: { info: DeploymentInfo }) {
  return (
    <section className="rounded-card border border-ink-100 bg-surface">
      <header className="border-b border-ink-100 px-4 py-3">
        <h3 className="text-sm font-semibold text-ink-900">
          Where are you installing it?
        </h3>
      </header>
      <div className="divide-y divide-ink-100">
        {info.platforms.map((platform) => (
          <details key={platform.platform} className="group px-4 py-2.5">
            <summary className="flex cursor-pointer list-none items-center justify-between gap-3 text-sm text-ink-900">
              <span className="flex items-center gap-2">
                <Globe aria-hidden className="size-3.5 text-ink-400" />
                {platform.platform}
              </span>
              {!platform.supports_javascript ? (
                <span className="rounded bg-warning-50 px-1.5 py-0.5 text-[10px] font-medium text-warning-700">
                  No custom scripts
                </span>
              ) : null}
            </summary>
            <ol className="mt-2 list-decimal space-y-1 pl-8 text-xs leading-relaxed text-ink-500">
              {platform.steps.map((step) => (
                <li key={step}>{step}</li>
              ))}
            </ol>
            {platform.note ? (
              <p className="mt-2 pl-8 text-[11px] italic text-warning-700">
                {platform.note}
              </p>
            ) : null}
          </details>
        ))}
      </div>
    </section>
  );
}

