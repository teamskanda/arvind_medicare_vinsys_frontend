/**
 * A live preview of the real thing.
 *
 * The iframe loads the same `panel_url` a visitor would, so what the customer
 * sees here is the actual published chatbot rather than a mock-up of one.
 * Before publishing it correctly shows the unavailable state — which is the
 * honest preview, and tells them the Publish button does something.
 */
function Preview({ info }: { info: DeploymentInfo }) {
  const { launcher } = info;

  return (
    <section className="rounded-card border border-ink-100 bg-surface lg:sticky lg:top-4 lg:self-start">
      <header className="border-b border-ink-100 px-4 py-3">
        <h3 className="text-sm font-semibold text-ink-900">Preview</h3>
        <p className="mt-1 text-xs text-ink-500">
          The real chatbot, loaded from its public URL.
        </p>
      </header>

      <div className="p-3">
        <div className="relative overflow-hidden rounded-lg border border-ink-100 bg-canvas">
          <iframe
            key={info.is_published ? "live" : "draft"}
            src={info.panel_url}
            title={`${info.chatbot_name} preview`}
            className="block h-[420px] w-full border-0 bg-surface"
            loading="lazy"
          />
        </div>

        <dl className="mt-3 space-y-1.5 text-[11px]">
          <Fact label="Launcher" value={`${launcher.launcher_size}px`} />
          <Fact
            label="Position"
            value={
              launcher.position === "bottom-left" ? "Bottom left" : "Bottom right"
            }
          />
          <Fact
            label="Chat window"
            value={`${launcher.window_width} × ${launcher.window_height}`}
          />
          <div className="flex items-baseline justify-between gap-3">
            <dt className="text-ink-500">Accent</dt>
            <dd className="flex items-center gap-1.5 font-medium text-ink-900">
              <span
                aria-hidden
                className="size-3 rounded-full border border-ink-900/15"
                style={{ backgroundColor: launcher.accent_color }}
              />
              {launcher.accent_color}
            </dd>
          </div>
        </dl>

        <p className="mt-3 border-t border-ink-100 pt-2.5 text-[11px] leading-relaxed text-ink-500">
          Change the icon, colour, size and position in the Customise tab.
          Publishing applies them to this URL and to every website where the
          snippet is already installed — nobody has to reinstall anything.
        </p>
      </div>
    </section>
  );
}
